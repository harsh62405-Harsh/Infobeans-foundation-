# Q1 -: The perimeter of a rectangle is 230 cm. If the length of the rectangle is 70 cm, find its breadth and area.
#  Perimeter of Rectangle = 2 * ( L + B )
# Area of Rectangle = L * B

Perimeter = 230
length = 70

breadth = (Perimeter/2) - length

area = length * breadth

print("Breadth =",breadth,"cm")
print("Area =", area ,"cm2")

